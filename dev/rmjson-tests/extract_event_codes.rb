#!/usr/bin/env ruby
# One-time generator: extracts the EVENT_COMMAND_CODES tables (format facts)
# from the legacy tool sources and writes event_codes.rb. Run before deletion.
require "fileutils"
APP = File.expand_path("../..", __dir__)
OLD = File.join(APP, "3rdParty/rmxp_translator")
OUT = File.join(APP, "www/php/plugins/rmvxace/bin/event_codes.rb")

ENGINES = { xp: "rmxp_db.rb", vx: "rmvx_db.rb", ace: "rmvxace_db.rb" }

tables = ENGINES.map do |sym, file|
  src = File.read(File.join(OLD, file))
  body = src[/EVENT_COMMAND_CODES\s*=\s*\{(.*?)\n\}/m, 1]
  raise "table not found in #{file}" unless body
  # flag is optional: a few XP/VX entries have no true/false flag
  entries = body.scan(/^\s*(\d+)\s*=>\s*\["([^"]+)"(?:,\s*(true|false))?\]/)
  raise "no entries parsed from #{file}" if entries.empty?
  # XP lists code 132 twice; legacy hash-literal semantics keep the last one
  entries = entries.reverse.uniq { |c, _, _| c }.reverse
  lines = entries.sort_by { |c, _, _| c.to_i }.map do |code, name, flag|
    "    #{code} => [#{name.inspect}, #{flag || 'false'}],"
  end
  "  :#{sym} => {\n#{lines.join("\n")}\n  }"
end.join(",\n")

FileUtils.mkdir_p(File.dirname(OUT))
File.binwrite(OUT, <<RUBY)
# event_codes.rb — generated by dev/rmjson-tests/extract_event_codes.rb from
# the legacy format documentation (command code -> [type name, translatable]).
# The type strings are load-bearing: the editor's skipElement feature filters
# on these exact values. Do not hand-edit.
module EventCodes
  TABLES = {
#{tables}
  }.freeze

  def self.for(engine)
    TABLES[engine]
  end
end
RUBY
puts "wrote #{OUT}"
